// JavaScript Conditionals
// =======================

const age = 20;

if (age >= 18) {
    console.log("You are an adult.");
} else {
    console.log("You are a minor.");
}

// Multiple conditions
const marks = 82;

if (marks >= 90) {
    console.log("Grade: A+");
} else if (marks >= 80) {
    console.log("Grade: A");
} else if (marks >= 70) {
    console.log("Grade: B");
} else if (marks >= 60) {
    console.log("Grade: C");
} else {
    console.log("Grade: F");
}

// Logical conditions
const username = "adhi";
const password = "1234";

if (username === "adhi" && password === "1234") {
    console.log("Login successful");
} else {
    console.log("Invalid credentials");
}
