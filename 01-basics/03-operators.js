// JavaScript Operators
// ====================

const a = 20;
const b = 5;

// Arithmetic operators
console.log("Addition:", a + b);
console.log("Subtraction:", a - b);
console.log("Multiplication:", a * b);
console.log("Division:", a / b);
console.log("Remainder:", a % b);

// Comparison operators
console.log("a > b:", a > b);
console.log("a < b:", a < b);
console.log("a >= b:", a >= b);
console.log("a <= b:", a <= b);

// Equality
console.log("5 == '5':", 5 == "5");
console.log("5 === '5':", 5 === "5");

// Not equal
console.log("5 != '5':", 5 != "5");
console.log("5 !== '5':", 5 !== "5");

// Logical operators
const age = 20;
const hasID = true;

console.log(age >= 18 && hasID);
console.log(age >= 18 || hasID);
console.log(!hasID);
